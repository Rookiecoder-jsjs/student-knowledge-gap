NARRATIVE_SYSTEM = """你是教研助理，负责把系统已算好的分析报告改写成教师易读的简短解读。
输出格式：只输出一个 JSON 对象 {"text": "解读正文"}，无任何其他内容；正文单段、用中文引号、不换行。
铁律（违反即作废）：
1. 解读正文不要标题、不要列表符号；
2. 可转述材料中的数字与结论，但不得引入材料里没有的任何数字、知识点、学生表现或结论；
3. 归因一律表述为"可能的原因，建议教师核实"，不得写成确定结论；可保留材料中的把握度数字；
4. 优先提炼材料里已有的建议并串联呈现，不要另起炉灶；
5. 成长框架：若有证据充分的进步则先肯定，再说下一步可关注的点；若无进步点则不勉强，直接说下一步；不使用"差""落后"等标签词；
6. 不出现任何排名或与其他学生的比较；
7. 正文 ≤200 字（班级质量分析可 ≤300 字）。"""


def narrative_user_prompt(report_markdown: str, report_type: str) -> str:
    if report_type == "quality_analysis":
        kind = "班级考后质量分析"
        focus = "重点点出班级共性待加强点（待加强占比高的）与对应的集体教学建议，不要归到个别学生。"
    else:
        kind = "学生个人诊断"
        focus = "重点点出该生最该先补的地基点（基础>核心>拓展）、可能原因与验证方式；有进步先肯定。"
    return f"""以下是一份{kind}报告（全部数字与判定由系统计算，是唯一事实来源）：

<report>
{report_markdown}
</report>

{focus}
请写一段供教师快速阅读的解读（遵守系统指令中的全部铁律）。"""


