# 题目模板覆盖的知识点全集（自检：应覆盖全学年非容器知识点）
ALL_TEMPLATE_KPS = {t["kps"][0] for tpls in QUESTION_BANK.values() for t in tpls}


def build_realistic_paper(
    kp_by_code: dict[str, Any],
    container_codes: list[str],
    exam_type: str,
    rng: random.Random,
) -> list[dict]:
    """按蓝图组一份真实试卷。

    参数:
        kp_by_code: code → KnowledgePoint（读取 difficulty_prior / importance）
        container_codes: 本场考试覆盖的章节容器 code（如 ["C7A-01", "C7A-02"]）
        exam_type: 诊断 | 单元 | 期中 | 期末
    返回: create_template 可接受的 questions 列表（idx 从 1 起）。
    """
    blue = BLUEPRINTS[exam_type]
    sections = blue["sections"]  # (标题, 题数, 每分/分值列表)
    # 各分区题位与逐题分值
    caps = [sec[1] if isinstance(sec[1], int) else len(sec[1]) for sec in sections]
    slots = sum(caps)
    score_spec = [sec[2] for sec in sections]  # int（选择/填空每分）或 list（解答逐题分）

    # 每章候选模板（按章聚合）与按题型索引
    chapter_templates: dict[str, list[dict]] = {}
    for cc in container_codes:
        chapter_templates[cc] = list(QUESTION_BANK.get(cc, []))
    all_templates = [t for ts in chapter_templates.values() for t in ts]
    by_type: dict[int, list[dict]] = {0: [], 1: [], 2: []}
    _TYPE_IDX = {"选择": 0, "填空": 1, "解答": 2}
    for t in all_templates:
        by_type[_TYPE_IDX[t["q_type"]]].append(t)

    def importance_weight(code: str) -> float:
        kp = kp_by_code.get(code)
        if kp is None:
            return 1.0
        return {"基础": 1.6, "核心": 1.3, "拓展": 0.9}.get(kp.importance, 1.0)

    # 1) 知识点主模板：知识点总数 ≤ 题位则全覆盖，否则按重要度抽样（每章保底 1 题）
    primary: dict[str, dict] = {}
    for cc in container_codes:
        for tpl in chapter_templates.get(cc, []):
            primary.setdefault(tpl["kps"][0], tpl)
    codes = list(primary)
    if len(codes) > slots:
        kept: dict[str, dict] = {}
        # 每章保底 1（该章最重要者）
        for cc in container_codes:
            cts = chapter_templates.get(cc, [])
            if cts:
                best = max(cts, key=lambda t: importance_weight(t["kps"][0]))
                kept[best["kps"][0]] = best
        # 分区配额：让选择/填空/解答各区先取「本区题型」的知识点（保真卷面结构，
        # 解答区不被选择题干淹没）。每区按题位取该题型下重要度最高的知识点。
        by_nat: dict[int, list[str]] = {0: [], 1: [], 2: []}
        for c in codes:
            by_nat[_TYPE_IDX[primary[c]["q_type"]]].append(c)
        for si in range(3):
            quota = max(0, caps[si] - sum(1 for k in kept if _TYPE_IDX[primary[k]["q_type"]] == si))
            for c in sorted(by_nat[si], key=lambda x: importance_weight(x), reverse=True):
                if quota <= 0 or len(kept) >= slots:
                    break
                if c not in kept:
                    kept[c] = primary[c]
                    quota -= 1
        # 剩余题位按重要度补齐（任何题型）
        for code in sorted(codes, key=lambda c: importance_weight(c), reverse=True):
            if len(kept) >= slots:
                break
            if code not in kept:
                kept[code] = primary[code]
        primary = kept
        codes = list(primary)

    # 2) 分区放置：知识点入自然题型区；自然区满则就近入「题型相近」的空位区
    #    （选择↔填空 互近，解答 独立），避免选择题干落入解答区。
    #    严格对齐分区题位（caps），总题数恒等于蓝图题位。
    _SPILL_ORDER = {0: (0, 1, 2), 1: (1, 0, 2), 2: (2, 0, 1)}
    placed: list[list[dict]] = [[], [], []]
    need = list(caps)
    for code in sorted(codes, key=lambda c: importance_weight(c), reverse=True):
        tpl = primary[code]
        si = _TYPE_IDX[tpl["q_type"]]
        chosen = si if need[si] > 0 else next(
            (k for k in _SPILL_ORDER[si] if need[k] > 0), None
        )
        if chosen is None:
            continue
        placed[chosen].append(tpl)
        need[chosen] -= 1

    # 3) 补齐各分区：优先取「本卷未用过」的同题型模板；池耗尽才复用——
    #    且只复用「有参数」的模板（参数重采样 → 题干不同），无参数模板每卷至多用 1 次。
    used_ids = {id(t) for sec in placed for t in sec}
    for si in range(3):
        pool = by_type[si] if by_type[si] else all_templates
        while need[si] > 0:
            fresh = [t for t in pool if id(t) not in used_ids]
            if fresh:
                w = [importance_weight(t["kps"][0]) for t in fresh]
                tpl = rng.choices(fresh, weights=w)[0]
            else:
                reusable = [t for t in pool if t["params"]]  # 有参数 → 可复用出不同题干
                pick = reusable or pool
                w = [importance_weight(t["kps"][0]) for t in pick]
                tpl = rng.choices(pick, weights=w)[0]
            placed[si].append(tpl)
            used_ids.add(id(tpl))
            need[si] -= 1

    # 4) 组卷 + 题干去重（重采样参数至多 3 次；无参数模板仍重复则保留，概率极低）。
    #    题型以分区为准（真实卷面「一、选择题」里就是选择题），模板题型在入区时对齐。
    section_types = ["选择", "填空", "解答"]
    used_stems: set[str] = set()
    questions: list[dict] = []
    idx = 1
    for si in (0, 1, 2):
        q_type = section_types[si]
        scores = score_spec[si]
        for j, tpl in enumerate(placed[si]):
            pool = by_type[si] if by_type[si] else all_templates
            # 题干去重：先重采样参数（参数区间小则多试几次），仍撞则换同区「有参数」模板
            for _attempt in range(12):
                params = _resolve_params(tpl, rng)
                stem, opts = _fmt(tpl["stem"], tpl.get("options"), params)
                if stem not in used_stems:
                    break
                swap_pool = [t for t in pool if t["params"]] or pool
                tpl = rng.choice(swap_pool)
            used_stems.add(stem)
            full_score = float(scores) if isinstance(scores, int) else float(scores[j])
            questions.append({
                "idx": idx, "stem": stem, "q_type": q_type,
                "full_score": full_score, "cog_level": tpl["cog"],
                "difficulty_est": tpl["difficulty"],
                "n_options": 4 if q_type == "选择" else None,
                "kps": [{"code": c, "weight": 1.0} for c in tpl["kps"]],
            })
            idx += 1

    return questions
