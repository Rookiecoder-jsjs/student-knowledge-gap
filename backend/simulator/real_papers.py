Q_TYPE_BY_COG = {"识记": "选择", "理解": "填空", "应用": "解答", "综合": "解答"}


def _t(
    stem: str,
    q_type: str,
    cog: str,
    kps: list[str],
    params: dict | None = None,
    options: list[str] | None = None,
    difficulty: float = 0.5,
) -> dict:
    """模板构造器（score 由蓝图决定，此处不带）。"""
    return {
        "stem": stem,
        "q_type": q_type,
        "cog": cog,
        "kps": kps,
        "params": params or {},
        "options": options,
        "difficulty": difficulty,
    }


def _resolve_params(tpl: dict, rng: random.Random) -> dict[str, Any]:
    """按 (min, max, step) 在合理区间内取样参数值；int 值视为固定常量。"""
    out: dict[str, Any] = {}
    for k, spec in tpl["params"].items():
        if isinstance(spec, int):  # 固定常量（如 科学记数法的 10 的指数）
            out[k] = spec
            continue
        lo, hi, step = spec
        # step 为整数 → 整数取样；否则保留 1 位小数
        n = int((hi - lo) // step) + 1
        v = lo + rng.randrange(n) * step
        out[k] = int(v) if step == int(step) and float(v).is_integer() else round(v, 1)
    return out


def _fmt(stem: str, opts: list[str] | None, params: dict[str, Any]) -> tuple[str, list[str] | None]:
    stem = stem.format(**params)
    opts = [o.format(**params) for o in opts] if opts else None
    return stem, opts


